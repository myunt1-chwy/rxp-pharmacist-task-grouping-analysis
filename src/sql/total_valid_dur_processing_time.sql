-- Aggregate the pre-P95 valid DUR table used by the model extract.
SELECT
    COUNT(*) AS N_VALID_DUR_TASKS,
    SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS,
    ROUND(
        SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) / 3600.0,
        2
    ) AS TOTAL_IMPUTED_HOURS,
    MIN(CAST(PROCESS_START_TIME AS DATE)) AS FIRST_PROCESS_DATE,
    MAX(CAST(PROCESS_START_TIME AS DATE)) AS LAST_PROCESS_DATE
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
