-- Direct lifecycle fact total: no employee, sequence, or validity joins.
SELECT
    COUNT(*) AS N_FACT_ROWS,
    COUNT(DISTINCT TO_VARCHAR(USER_ID) || '|' || TO_VARCHAR(TASK_ID)) AS N_TASK_KEYS,
    SUM(DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_SECONDS,
    ROUND(SUM(DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) / 3600.0, 2) AS TOTAL_HOURS
FROM EDLDB.PET_HEALTH_ANALYTICS_SANDBOX.FCT__TASKS_LIFECYCLE
WHERE TASK_CREATED_AT >= '2026-02-01'
  AND TASK_CREATED_AT < '2026-08-01'
  AND TASK_TYPE = 'DUR'
  AND HANDOFF_TYPE IS NULL
  AND DWELL_IN_PROGRESS_TO_CLOSED_SECONDS > 156.608019
