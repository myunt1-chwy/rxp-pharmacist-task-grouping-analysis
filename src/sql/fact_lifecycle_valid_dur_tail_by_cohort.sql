-- Use valid-DUR keys only to identify the model population; take cohort and
-- raw duration from FCT__TASKS_LIFECYCLE to verify reported tail totals.
WITH valid_tail_keys AS (
    SELECT USER_ID, TASK_ID, COH,
           IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS VALID_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
    WHERE IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS >= 156.608019
), fact_rows AS (
    SELECT
        l.USER_ID,
        l.TASK_ID,
        COALESCE(NULLIF(TRIM(l.ITEM_COHORT), ''), '<Missing>') AS COHORT,
        l.DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS RAW_SECONDS,
        v.COH AS VALID_COHORT,
        v.VALID_SECONDS
    FROM EDLDB.PET_HEALTH_ANALYTICS_SANDBOX.FCT__TASKS_LIFECYCLE AS l
    JOIN valid_tail_keys AS v
      ON v.USER_ID = l.USER_ID
     AND v.TASK_ID = l.TASK_ID
    WHERE l.TASK_CREATED_AT >= '2026-02-01'
      AND l.TASK_CREATED_AT < '2026-08-01'
      AND l.TASK_TYPE = 'DUR'
      AND l.HANDOFF_TYPE IS NULL
)
SELECT
    COHORT,
    COUNT(*) AS N_FACT_ROWS,
    COUNT(DISTINCT TO_VARCHAR(USER_ID) || '|' || TO_VARCHAR(TASK_ID)) AS N_TASK_KEYS,
    COUNT_IF(RAW_SECONDS IS NULL) AS N_NULL_RAW_SECONDS,
    COUNT_IF(RAW_SECONDS <> VALID_SECONDS) AS N_DURATION_MISMATCHES,
    COUNT_IF(COHORT <> VALID_COHORT) AS N_COHORT_MISMATCHES,
    SUM(RAW_SECONDS) AS TOTAL_RAW_SECONDS,
    ROUND(SUM(RAW_SECONDS) / 3600.0, 2) AS TOTAL_RAW_HOURS
FROM fact_rows
GROUP BY COHORT
ORDER BY N_FACT_ROWS DESC
