SELECT
    TASK_TYPE,
    COALESCE(NULLIF(TRIM(HANDOFF_TYPE), ''), '<Missing>') AS HANDOFF_TYPE,
    COUNT(*) AS N_TASKS,
    COUNT_IF(HANDOFF_REASON IS NOT NULL) AS N_WITH_HANDOFF_REASON,
    SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
GROUP BY 1, 2
ORDER BY TASK_TYPE, N_TASKS DESC
