-- Summarize the full null-handoff DUR population and the valid-DUR
-- above-cutoff tail that contributes 24,710.67 reported hours.
WITH durations AS (
    SELECT
        'All null-handoff DURs' AS POPULATION,
        TASK_ID,
        USER_ID,
        DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS RAW_SECONDS,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
    WHERE TASK_TYPE = 'DUR'
      AND HANDOFF_TYPE IS NULL

    UNION ALL

    SELECT
        'Valid DURs at or above cutoff' AS POPULATION,
        TASK_ID,
        USER_ID,
        NULL AS RAW_SECONDS,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
    WHERE IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS >= 156.608019
)
SELECT
    POPULATION,
    COUNT(*) AS N_DURS,
    COUNT(DISTINCT TO_VARCHAR(USER_ID) || '|' || TO_VARCHAR(TASK_ID)) AS N_TASK_KEYS,
    IFF(POPULATION = 'All null-handoff DURs',
        COUNT_IF(RAW_SECONDS IS NULL), NULL) AS N_IMPUTED,
    SUM(DURATION_SECONDS) AS TOTAL_SECONDS,
    ROUND(SUM(DURATION_SECONDS) / 3600.0, 2) AS TOTAL_HOURS,
    ROUND(AVG(DURATION_SECONDS), 2) AS MEAN_SECONDS,
    MEDIAN(DURATION_SECONDS) AS MEDIAN_SECONDS,
    APPROX_PERCENTILE(DURATION_SECONDS, 0.90) AS P90_SECONDS,
    APPROX_PERCENTILE(DURATION_SECONDS, 0.95) AS P95_SECONDS,
    APPROX_PERCENTILE(DURATION_SECONDS, 0.99) AS P99_SECONDS,
    MAX(DURATION_SECONDS) AS MAX_SECONDS
FROM durations
GROUP BY POPULATION
ORDER BY POPULATION
