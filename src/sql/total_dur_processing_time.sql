SELECT
    COUNT(*) AS N_DUR_TASKS,
    SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS,
    ROUND(
        SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) / 3600.0,
        2
    ) AS TOTAL_IMPUTED_HOURS,
    COUNT_IF(DWELL_IN_PROGRESS_TO_CLOSED_SECONDS IS NULL) AS N_IMPUTED_DURATIONS,
    MIN(PROCESS_START_DATE) AS FIRST_PROCESS_DATE,
    MAX(PROCESS_START_DATE) AS LAST_PROCESS_DATE
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
WHERE TASK_TYPE = 'DUR';
