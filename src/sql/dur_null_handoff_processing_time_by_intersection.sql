-- Count DUR tasks with no handoff type, without model or validity filters.
SELECT
    CASE
        WHEN sequence.N_INTERSECTING_TASKS > 0 THEN 'Intersecting'
        WHEN sequence.N_INTERSECTING_TASKS = 0 THEN 'Not intersecting'
        ELSE 'No sequence record'
    END AS INTERSECTION_STATUS,
    COUNT(*) AS N_DUR_TASKS,
    SUM(task.IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS,
    ROUND(
        SUM(task.IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) / 3600.0,
        2
    ) AS TOTAL_IMPUTED_HOURS
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS AS task
LEFT JOIN EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS_WITH_SEQUENCE AS sequence
    ON sequence.USER_ID = task.USER_ID
   AND sequence.TASK_ID = task.TASK_ID
WHERE task.TASK_TYPE = 'DUR'
  AND task.HANDOFF_TYPE IS NULL
GROUP BY 1
ORDER BY 1
