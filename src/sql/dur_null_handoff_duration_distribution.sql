-- Compare the full null-handoff DUR population with its valid-DUR subset.
-- Buckets use imputed processing seconds and separate the model cutoff.
WITH durations AS (
    SELECT
        'All null-handoff DURs' AS POPULATION,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
    WHERE TASK_TYPE = 'DUR'
      AND HANDOFF_TYPE IS NULL

    UNION ALL

    SELECT
        'Valid DURs' AS POPULATION,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
), bucketed AS (
    SELECT
        POPULATION,
        DURATION_SECONDS,
        CASE
            WHEN DURATION_SECONDS <= 0 THEN 0
            WHEN DURATION_SECONDS < 30 THEN 1
            WHEN DURATION_SECONDS < 60 THEN 2
            WHEN DURATION_SECONDS < 120 THEN 3
            WHEN DURATION_SECONDS < 156.608019 THEN 4
            WHEN DURATION_SECONDS < 300 THEN 5
            WHEN DURATION_SECONDS < 600 THEN 6
            WHEN DURATION_SECONDS < 1800 THEN 7
            WHEN DURATION_SECONDS < 3600 THEN 8
            WHEN DURATION_SECONDS < 14400 THEN 9
            ELSE 10
        END AS BUCKET_ORDER
    FROM durations
)
SELECT
    POPULATION,
    BUCKET_ORDER,
    CASE BUCKET_ORDER
        WHEN 0 THEN '0 or negative seconds'
        WHEN 1 THEN '1-29 seconds'
        WHEN 2 THEN '30-59 seconds'
        WHEN 3 THEN '60-119 seconds'
        WHEN 4 THEN '120-156 seconds'
        WHEN 5 THEN '157-299 seconds'
        WHEN 6 THEN '300-599 seconds'
        WHEN 7 THEN '600-1,799 seconds'
        WHEN 8 THEN '1,800-3,599 seconds'
        WHEN 9 THEN '3,600-14,399 seconds'
        ELSE '14,400+ seconds'
    END AS DURATION_BUCKET,
    COUNT(*) AS N_DURS,
    SUM(DURATION_SECONDS) AS TOTAL_SECONDS,
    ROUND(SUM(DURATION_SECONDS) / 3600.0, 2) AS TOTAL_HOURS,
    MIN(DURATION_SECONDS) AS MIN_SECONDS,
    MAX(DURATION_SECONDS) AS MAX_SECONDS
FROM bucketed
GROUP BY POPULATION, BUCKET_ORDER
ORDER BY POPULATION, BUCKET_ORDER
