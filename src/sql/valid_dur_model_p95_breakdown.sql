-- Split the valid DUR table at the model's approximate P95 cutoff.
SELECT
    IFF(
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS < 156.608019,
        'Below model cutoff',
        'At or above model cutoff'
    ) AS DURATION_BUCKET,
    COUNT(*) AS N_VALID_DUR_TASKS,
    SUM(IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
GROUP BY 1
ORDER BY 1
