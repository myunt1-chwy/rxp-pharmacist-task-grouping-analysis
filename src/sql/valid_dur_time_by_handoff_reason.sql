-- Valid DUR rows do not carry HANDOFF_REASON; join it from MY_RXP_TASKS.
-- Group source rows by task key before joining so duplicate source rows cannot
-- multiply valid-DUR processing time.
WITH task_reasons AS (
    SELECT
        USER_ID,
        TASK_ID,
        MIN(HANDOFF_REASON) AS HANDOFF_REASON,
        COUNT(*) AS N_SOURCE_ROWS,
        COUNT(DISTINCT HANDOFF_REASON) AS N_DISTINCT_REASONS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
    GROUP BY USER_ID, TASK_ID
)
SELECT
    COALESCE(NULLIF(TRIM(task_reasons.HANDOFF_REASON), ''), '<Missing>') AS HANDOFF_REASON,
    COUNT(*) AS N_VALID_DUR_TASKS,
    SUM(valid.IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) AS TOTAL_IMPUTED_SECONDS,
    ROUND(SUM(valid.IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS) / 3600.0, 2)
        AS TOTAL_IMPUTED_HOURS,
    COUNT_IF(task_reasons.TASK_ID IS NULL) AS N_UNMATCHED_TASKS,
    COUNT_IF(task_reasons.N_SOURCE_ROWS > 1) AS N_DUPLICATE_SOURCE_KEYS,
    COUNT_IF(task_reasons.N_DISTINCT_REASONS > 1) AS N_CONFLICTING_REASONS
FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS AS valid
LEFT JOIN task_reasons
    ON task_reasons.USER_ID = valid.USER_ID
   AND task_reasons.TASK_ID = valid.TASK_ID
GROUP BY 1
ORDER BY TOTAL_IMPUTED_SECONDS DESC
