-- Cohorts for the high-duration tail in the full null-handoff population
-- and in the narrower valid-DUR model population.
WITH tail AS (
    SELECT
        'All null-handoff DURs' AS POPULATION,
        COALESCE(NULLIF(TRIM(TO_VARCHAR(COH)), ''), '<Missing>') AS COHORT,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_TASKS
    WHERE TASK_TYPE = 'DUR'
      AND HANDOFF_TYPE IS NULL
      AND IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS >= 156.608019

    UNION ALL

    SELECT
        'Valid DURs' AS POPULATION,
        COALESCE(NULLIF(TRIM(TO_VARCHAR(COH)), ''), '<Missing>') AS COHORT,
        IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS AS DURATION_SECONDS
    FROM EDLDB_DEV.PET_HEALTH_ANALYTICS_SANDBOX.MY_RXP_VALID_DUR_TASKS
    WHERE IMPUTED_DWELL_IN_PROGRESS_TO_CLOSED_SECONDS >= 156.608019
)
SELECT
    POPULATION,
    COHORT,
    COUNT(*) AS N_DURS,
    SUM(DURATION_SECONDS) AS TOTAL_SECONDS,
    ROUND(SUM(DURATION_SECONDS) / 3600.0, 2) AS TOTAL_HOURS,
    ROUND(AVG(DURATION_SECONDS), 2) AS MEAN_SECONDS,
    MEDIAN(DURATION_SECONDS) AS MEDIAN_SECONDS
FROM tail
GROUP BY POPULATION, COHORT
ORDER BY POPULATION, N_DURS DESC
